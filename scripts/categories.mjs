// Для непродуктових: спершу непродуктові групи.
const NONFOOD = [HOME_EARLY, PETS, KIDS, BEAUTY, CHEM, HOME];

function run(rules, text) {
  if (!text) return null;
  for (const [cat, re] of rules) if (re.test(text)) return cat;
  return null;
}

export const classifyText = text => run(FOOD_ORDER, text);

// Спершу категорія магазину, потім назва товару.
// nonFood=true — для магазинів на кшталт Аврори, де «Гарбуз» частіше декор, ніж овоч.
export function classify(storeCategory, title, nonFood = false) {
  if (nonFood) {
    return run(NONFOOD, storeCategory) || run(FOOD_ORDER, storeCategory) ||
           run(NONFOOD, title) || run(FOOD_ORDER, title) || "other";
  }
  return run(FOOD_ORDER, storeCategory) || run(FOOD_ORDER, title) || "other";
}

