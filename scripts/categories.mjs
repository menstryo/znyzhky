export function silpoRootCategory(rootSlug, leafPath) {
  const base = String(rootSlug || "").replace(/-\d+$/, "");
  let cat = SILPO_ROOTS[base];
  if (cat === undefined) return null;
  // «Для дому» містить побутову хімію
  if (cat === "home" && /khimi|prann|chyst|myt|prybyr|plia/.test(leafPath || "")) cat = "chem";
  return cat;
}
